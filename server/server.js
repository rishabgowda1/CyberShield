'use strict';
const path = require('path');
const express = require('express');
const helmet = require('helmet');
const rateLimit = require('express-rate-limit');

const config = require('./config');
const { AppError } = require('./errors');
const phishing = require('./services/phishing');
const store = require('./services/store');

const app = express();
app.set('trust proxy', config.trustProxy ? 1 : false);
app.disable('x-powered-by');

app.use(helmet({
  contentSecurityPolicy: {
    directives: {
      defaultSrc: ["'self'"], scriptSrc: ["'self'"], styleSrc: ["'self'"], imgSrc: ["'self'", 'data:'],
      connectSrc: ["'self'"], objectSrc: ["'none'"], frameAncestors: ["'none'"], baseUri: ["'self'"], formAction: ["'self'"],
      // helmet's default adds upgrade-insecure-requests, which breaks http://localhost in Safari – disabled on purpose.
      upgradeInsecureRequests: null,
    },
  },
}));
app.use(express.json({ limit: '10kb' }));

/* Anonymous per-browser identity (no login): a random UUID generated by the client and sent in a header. */
app.use('/api', (req, _res, next) => {
  const id = req.get('x-client-id');
  req.clientId = id && /^[a-zA-Z0-9-]{8,64}$/.test(id) ? id : null;
  next();
});

const limiter = (max) => rateLimit({
  windowMs: 60 * 1000, limit: max, standardHeaders: true, legacyHeaders: false,
  handler: (_req, res) => res.status(429).json({ success: false, error: { code: 'RATE_LIMITED', message: 'Too many requests. Please wait a minute and try again.' } }),
});

app.get('/api/health', (_req, res) => {
  res.json({ success: true, status: 'online', version: require('../package.json').version, uptimeSeconds: Math.round(process.uptime()),
    phishingDataset: phishing.status(), time: new Date().toISOString() });
});
app.use('/api/scan', limiter(15), require('./routes/scan'));
app.use('/api/phishing', limiter(60), require('./routes/phishing'));
app.use('/api/network', limiter(30), require('./routes/network'));
app.use('/api/history', limiter(120), require('./routes/history'));
app.use('/api', (_req, _res, next) => next(new AppError('API endpoint not found.', 'NOT_FOUND', 404)));

/* Static client. No wildcard route is used, so there is nothing for path-to-regexp to choke on. */
app.use(express.static(path.join(__dirname, '..', 'client')));
app.use((_req, res) => res.status(404).type('text').send('Not found'));

/* Central error handler: always JSON, never a stack trace. */
// eslint-disable-next-line no-unused-vars
app.use((err, _req, res, _next) => {
  if (err && err.type === 'entity.parse.failed') err = new AppError('Request body is not valid JSON.', 'BAD_JSON');
  if (err && err.type === 'entity.too.large') err = new AppError('Request body is too large.', 'TOO_LARGE', 413);
  if (err && err.expose) return res.status(err.status || 400).json({ success: false, error: { code: err.code, message: err.message } });
  console.error('[error]', err);
  res.status(500).json({ success: false, error: { code: 'INTERNAL', message: 'Something went wrong on the server.' } });
});

if (require.main === module) {
  store.init().catch(() => {});
  phishing.load().then((s) => console.log(`[phishing] dataset ${s.loaded ? `loaded (${s.entries} entries)` : `not loaded: ${s.error}`}`))
    .catch((e) => console.error('[phishing] load failed:', e.message));
  const server = app.listen(config.port, () => console.log(`CyberShield running at http://localhost:${config.port}`));
  server.on('error', (e) => {
    if (e.code === 'EADDRINUSE') console.error(`Port ${config.port} is already in use. Stop the other server or run with PORT=3001.`);
    else console.error(e);
    process.exit(1);
  });
}

module.exports = app;
